#!/usr/bin/env python3
"""Перекомпоновка vkr_master.txt -> vkr_final.txt
Делает:
1) Перемещает блок "Стратегически значимые различия / Параметры / Сочетания / Демопортфель" из текущих 2.3-2.4 в позицию 2.1.3 ПЕРЕД 2.2 Анализ внутренней среды.
2) Перенумеровывает: сценарии -> 2.3, выводы -> 2.4.
3) Обновляет оглавление.
4) Чистит R-метки: убирает R3 (Сокращение), R4а/R4б, подтипы 4а/4б.
5) Чистит длинные тире (— → –) и обрывки фраз.
6) Чистит кросс-ссылки в Главе 3 (§2.7→§2.3 (сценарии), §2.8→§2.3, §2.4.1→§2.1.3, §3.8→§3.4, §3.7→§3.2, §3.3→§3.2 где про УПС).
"""
import re
from pathlib import Path

SRC = Path('/workspace/vkr/vkr_master.txt')
DST = Path('/workspace/vkr/vkr_final.txt')

text = SRC.read_text(encoding='utf-8')
lines = text.splitlines(keepends=False)

# --- 1. Найти границы блоков, которые надо перемещать ---
def find_line(pattern, start=0):
    for i in range(start, len(lines)):
        if re.search(pattern, lines[i]):
            return i
    return -1

# В тексте после "ГЛАВА 2" идёт:
# 2.1 Анализ внешней макросреды
# 2.1.1 PESTEL
# 2.1.2 Конкурентный анализ
# (пусто)
# 2.2 Анализ внутренней среды
# (пусто)
# 2.3 Стратегически значимые различия... <-- A_start
# 2.3 Параметры...
# 2.3.1-2.3.4
# 2.4 Демонстрационный портфель
# (...) <-- A_end (последняя строка демопортфеля)
# 2.5 Три сценария <-- B_start
# 2.6 Сопоставление
# 2.7 Выводы
# ГЛАВА 3

idx_glava2 = find_line(r'^ГЛАВА 2\.')
idx_21 = find_line(r'^2\.1\s+Анализ внешней', idx_glava2)
idx_211 = find_line(r'^2\.1\.1\s+PESTEL', idx_21)
idx_212 = find_line(r'^2\.1\.2\s+Конкурентный', idx_211)
idx_22 = find_line(r'^2\.2\s+Анализ внутренней', idx_212)
# Блок A: от "2.3 Стратегически значимые различия" до конца §2.4 (демопортфеля)
idx_A_start = find_line(r'^2\.3\s+Стратегически значимые различия', idx_22)
idx_25 = find_line(r'^2\.5\s+Три сценария', idx_A_start)
idx_26 = find_line(r'^2\.6\s+Сопоставление', idx_25)
idx_27 = find_line(r'^2\.7\s+Выводы по второй главе', idx_26)
idx_glava3 = find_line(r'^ГЛАВА 3\.', idx_27)

print(f"ГЛАВА 2 at line {idx_glava2}")
print(f"2.1 at {idx_21}, 2.1.1 at {idx_211}, 2.1.2 at {idx_212}")
print(f"2.2 at {idx_22}")
print(f"A_start (2.3 различия) at {idx_A_start}")
print(f"2.5 (сценарии) at {idx_25}")
print(f"2.6 (сопоставление) at {idx_26}")
print(f"2.7 (выводы) at {idx_27}")
print(f"ГЛАВА 3 at {idx_glava3}")

# Конец блока A = строка перед 2.5
idx_A_end_excl = idx_25  # exclusive

# Блок A (вырезаем): диапазон [idx_A_start, idx_A_end_excl)
block_A = lines[idx_A_start:idx_A_end_excl]
# Блок B (сценарии + сопоставление + старые выводы): [idx_25, idx_glava3)
block_B = lines[idx_25:idx_glava3]

# До блока 2.2 — то, что было перед "2.2 Анализ внутренней среды"
pre_22 = lines[:idx_22]
# Блок 2.2 — внутренняя среда: [idx_22, idx_A_start)
block_22 = lines[idx_22:idx_A_start]

# ---- 2. Переименование блока A в подсекции 2.1.3 ----
# Старая нумерация в block_A:
# "2.3 Стратегически значимые различия между региональными рынками: принцип отбора"
# "2.3 Параметры рыночной конфигурации, которые меняют реализуемость базовой конкурентной модели"  (дубль)
# "2.3.1 Структурная конфигурация рынка (I уровень)"
# "2.3.2 Операционная исполнимость базовой модели (II уровень)"
# "2.3.3 Тактические рычаги управления присутствием (III уровень)"
# "2.3.4 Сочетание факторов как основа стратегически значимого различения рынков"
# "2.4 Демонстрационный портфель: сочетания факторов на пяти рынках"
# Новая нумерация — это всё внутри 2.1.3:
# "2.1.3 Стратегически значимые различия между региональными рынками"
# (внутри без подсекций; параграфы — с буквенной/тематической разметкой)
# Чтобы не плодить вложенность, делаю заголовки уровня 2.1.3.X:
# 2.1.3   Стратегически значимые различия между региональными рынками: принцип отбора
# 2.1.3.1 Параметры рыночной конфигурации, меняющие реализуемость базовой конкурентной модели
# 2.1.3.2 Структурная конфигурация рынка (I уровень)
# 2.1.3.3 Операционная исполнимость базовой модели (II уровень)
# 2.1.3.4 Тактические рычаги управления присутствием (III уровень)
# 2.1.3.5 Сочетание факторов как основа стратегически значимого различения рынков
# 2.1.3.6 Демонстрационный портфель: сочетания факторов на пяти рынках

renames_A = [
    (r'^2\.3\s+Стратегически значимые различия между региональными рынками: принцип отбора$',
     '2.1.3 Стратегически значимые различия между региональными рынками: принцип отбора'),
    (r'^2\.3\s+Параметры рыночной конфигурации, которые меняют реализуемость базовой конкурентной модели$',
     '2.1.3.1 Параметры рыночной конфигурации, меняющие реализуемость базовой конкурентной модели'),
    (r'^2\.3\.1\s+Структурная конфигурация рынка \(I уровень\)$',
     '2.1.3.2 Структурная конфигурация рынка (I уровень)'),
    (r'^2\.3\.2\s+Операционная исполнимость базовой модели \(II уровень\)$',
     '2.1.3.3 Операционная исполнимость базовой модели (II уровень)'),
    (r'^2\.3\.3\s+Тактические рычаги управления присутствием \(III уровень\)$',
     '2.1.3.4 Тактические рычаги управления присутствием (III уровень)'),
    (r'^2\.3\.4\s+Сочетание факторов как основа стратегически значимого различения рынков$',
     '2.1.3.5 Сочетание факторов как основа стратегически значимого различения рынков'),
    (r'^2\.4\s+Демонстрационный портфель: сочетания факторов на пяти рынках$',
     '2.1.3.6 Демонстрационный портфель: сочетания факторов на пяти рынках'),
    (r'^Таблица 2\.4\.1\. ',
     'Таблица 2.1.3.1. '),
]

new_block_A = []
for ln in block_A:
    new_ln = ln
    for pat, repl in renames_A:
        new_ln = re.sub(pat, repl, new_ln)
    new_block_A.append(new_ln)

# ---- 3. Переименование блока B (сценарии) -> 2.3 ----
renames_B = [
    (r'^2\.5\s+Три сценария обращения с портфелем региональных рынков$',
     '2.3 Стратегический выбор'),
    # Подзаголовок «Три сценария» — оставим как абзац или сделаем 2.3.1
    (r'^2\.6\s+Сопоставление сценариев по пяти критериям и обоснование выбора$',
     '2.3.1 Сопоставление сценариев по пяти критериям и обоснование выбора'),
    (r'^2\.7\s+Выводы по второй главе$',
     '2.4 Выводы по второй главе'),
]

new_block_B = []
for ln in block_B:
    new_ln = ln
    for pat, repl in renames_B:
        new_ln = re.sub(pat, repl, new_ln)
    new_block_B.append(new_ln)

# ---- 4. Переименование 2.2 (внутренняя среда) ----
new_block_22 = []
for ln in block_22:
    new_ln = re.sub(r'^2\.2\s+Анализ внутренней среды; cтратегическая позиция МТС Юрент и постановка задачи стратегического выбора$',
                    '2.2 Анализ внутренней среды и стратегическая позиция МТС Юрент',
                    ln)
    new_block_22.append(new_ln)

# ---- 5. Сборка ----
# Новый порядок:
# pre_22 (до старого 2.2) + new_block_A (=2.1.3) + new_block_22 (=2.2) + new_block_B (=2.3/2.4) + tail (ГЛАВА 3 и далее)
tail = lines[idx_glava3:]
new_lines = pre_22 + new_block_A + new_block_22 + new_block_B + tail

# ---- 6. Глобальные чистки на всём тексте ----
new_text = '\n'.join(new_lines)

# 6.1 Длинные тире в обычные короткие
# Заменяем em-dash (—, U+2014) и horizontal bar (―, U+2015) на en-dash (–, U+2013)
# Сохраняем существующие en-dash как есть.
# Внимание: между цифрами (2024—2025) → en-dash тоже корректен (по ГОСТ интервалы через en-dash).
new_text = new_text.replace('—', '–')

# 6.2 R-метки чистка
# Убрать R4а/R4б — заменить на R3
new_text = new_text.replace('R4а', 'R3')
new_text = new_text.replace('R4б', 'R3')
# "R3 (Сокращение)" → "R3 (ограниченное удержание)" внутри R3
new_text = new_text.replace('R3 (Сокращение)', 'R3 (ограниченная форма)')

# 6.3 «подтипы 4а ограниченный вход и 4б ограниченное удержание» — упрощаем
new_text = re.sub(
    r'\(с подтипами 4а ограниченный вход и 4б ограниченное удержание\)',
    '(с ограниченной формой удержания на регуляторно тяжёлых рынках)',
    new_text
)

# 6.4 Кросс-ссылки в Главе 3 и заключении
# §2.7 (сценарии) → §2.3
# §2.8 (сопоставление) → §2.3.1
# §2.4.1 (демопортфель) → §2.1.3.6
# §3.8 (компенсаторы) → §3.4
# §3.7 (УПС) → §3.2
# §3.3 (УПС в тексте) — оставляем как §3.2; но "§3.3" в §3.3 финкарте — это сам §3.3, не трогаем
# Конкретные паттерны:
new_text = re.sub(r'§\s*2\.7\s*\(Три сценария\)', '§2.3 (Стратегический выбор)', new_text)
new_text = re.sub(r'§\s*2\.7', '§2.3', new_text)
new_text = re.sub(r'§\s*2\.8\s*,?\s*критерий 3', '§2.3.1, критерий 3', new_text)
new_text = re.sub(r'§\s*2\.8', '§2.3.1', new_text)
new_text = re.sub(r'§\s*2\.4\.1', '§2.1.3.6', new_text)
new_text = re.sub(r'§\s*3\.8', '§3.4', new_text)
# "§ 3.7" в таблице -> "§ 3.2" (УПС)
new_text = re.sub(r'§\s*3\.7', '§3.2', new_text)
# Внутри §3.2 (УПС) есть ссылки на "§3.3 как способ" — это сам УПС, должен быть §3.2; чистим
new_text = re.sub(r'инструменты\s*§\s*3\.3\)', 'инструменты §3.2)', new_text)
new_text = re.sub(r'\(включая инструменты\s*§\s*3\.3\)', '(включая инструменты §3.2)', new_text)
new_text = re.sub(r'рассматривается в\s*§\s*3\.3\s+как способ', 'рассматривается в §3.2 как способ', new_text)
# В §3.2 ссылка "(§ 3.3)" внутри УПС про сами же стимулы:
new_text = re.sub(r'трёх типов стимулов \(на стороне точки высадки, точки посадки, внешнего исполнителя\s*–\s*§\s*3\.3\)',
                  'трёх типов стимулов (на стороне точки высадки, точки посадки, внешнего исполнителя)',
                  new_text)
# Оставшиеся §3.3 — это финкарта (правильно), не трогаем

# 6.5 Чистка явных обрывков
# "научный руководитель ВКР; )" — переписываем фрагмент про экспертов
# Текущая конструкция методов сильно поломана списком. Перепишем целиком ниже отдельным StrReplace на финальном тексте.

# 6.6 «по совокупности критериев … по совокупности критериев» — дубль
new_text = re.sub(
    r'является предпочтительным по совокупности критериев «сохранение единой логики» и «единый режим с операционной адаптацией» по совокупности критериев ',
    'является предпочтительным по сравнению со сценариями «сохранение единой логики» и «единый режим с операционной адаптацией» по совокупности критериев ',
    new_text
)

# 6.7 «выводимым из теоретико-методологической основы (выводимым из теоретико-методологической основы работы)» — дубль
new_text = re.sub(
    r'выводимым из теоретико-методологической основы \(выводимым из теоретико-методологической основы работы\)',
    'выводимым из теоретико-методологической основы работы',
    new_text
)

# 6.8 «Гид интервью и расшифровки в согласованной мере раскрытия приведены .»
new_text = re.sub(
    r'Гид интервью и расшифровки в согласованной мере раскрытия приведены\s*\.',
    'Гид интервью и расшифровки в согласованной мере раскрытия приведены в Приложении Б.',
    new_text
)

# 6.9 «.ру» → возможно «ЮрентБайк.ру» с точкой — оставим
# в работе есть «ООО "ЮрентБайк.ру"» — это нормально

# ---- 7. Сохранить ----
DST.write_text(new_text, encoding='utf-8')
print(f"Saved to {DST}, {len(new_text)} chars, {new_text.count(chr(10))} lines")
