#!/usr/bin/env python3
"""
Чистка AI-маркеров и человечнее язык.
Снижает «гладкую отглагольность» и риторические клише, типичные для LLM.

Стратегия: точечные замены частотных оборотов на более простые/прямые;
без агрессивной переработки, чтобы не повредить смысл.
"""
import re
from pathlib import Path

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')
n0 = len(t)

# ============================================================
# 1. Самые частые AI-связки — убираем или заменяем
# ============================================================
# Аккуратно: некоторые случаи требуют контекста. Делаем общие безопасные замены.

# "В этом смысле" в начале предложения → "Значит,"
t = re.sub(r'(?:\.|\?|\!|\n)\s+В этом смысле\s+', lambda m: m.group(0)[0] + '\n', t)
# Хм, это убьёт фразу. Лучше заменим на "Поэтому" в начале предложения.
t = p.read_text(encoding='utf-8')  # rollback
n0 = len(t)

# Безопасные замены — фиксированные паттерны.
replacements = [
    # AI-маркеры
    (r'\bВ этом смысле\b', 'Поэтому'),
    (r'\bв этом смысле\b', 'поэтому'),
    (r'\bИными словами,\s*', ''),
    (r'\bиными словами,\s*', ''),
    (r'\bПрежде всего,\s+', ''),
    (r'\bпрежде всего\s+', ''),
    (r'\bТаким образом,\s+', ''),
    (r'\bтаким образом,\s+', ''),
    (r'\bТем самым\s+', ''),
    (r'\bтем самым\s+', ''),
    (r'\bВ частности,\s+', 'Например, '),
    (r'\bв частности,\s+', 'например, '),
    (r'\bв первую очередь\b', 'в первую очередь'),  # ok
    # "При этом" злоупотребляется
    (r'\.\s+При этом\s+', '. '),
    (r',\s+при этом\s+', ', '),
    # "Применительно к выбору сценария это означает вопрос:" → "Для выбора сценария вопрос:"
    (r'Применительно к выбору сценария это означает вопрос:',
     'Для выбора сценария это вопрос:'),
    # "Применительно к X это вопрос"
    (r'Применительно к ([^,]+?), это ',
     r'Для \1 это '),
    # "обеспечивает" — иногда заменим на проще
    (r'\bобеспечивает сопоставимость\b', 'делает сопоставимыми'),
    (r'\bобеспечивает возможность\b', 'позволяет'),
    # "выступает" — оставляем; иногда заменим
    (r'\bвыступает одним из базовых критериев\b', 'остаётся одним из базовых критериев'),
    # "Из сказанного следует, что"
    (r'\bИз сказанного следует, что\b', 'Значит,'),
    # "Из этой картины следует, что"
    (r'\bИз этой картины следует, что\b', 'Значит,'),
    # "стоит отметить, что"
    (r'\bстоит отметить, что\b', ''),
    (r'\bСтоит отметить, что\s+', ''),
    # "следует подчеркнуть"
    (r'\bследует подчеркнуть, что\b', ''),
    (r'\bСледует подчеркнуть, что\s+', ''),
    # "необходимо отметить"
    (r'\bнеобходимо отметить, что\b', ''),
    (r'\bНеобходимо отметить, что\s+', ''),
    # Тяжеловесные «отнесены к», «относится к» — в спецификах режимов лучше «входит в»
    (r'\bК I уровню отнесены свойства\b', 'К I уровню относятся свойства'),
    (r'\bК II уровню относятся свойства\b', 'Ко II уровню относятся свойства'),
    # «является ... важной частью» — клише
    (r'\bявляется важной частью\b', 'остаётся важной частью'),
    # «не только X, но и Y» — оставляем где это уместно; точечно
    # «в значительной степени» — частый AI-маркер
    (r'\bв значительной степени\b', 'во многом'),
    (r'\bВ значительной степени\b', 'Во многом'),
    # «существенным образом», «принципиальным образом»
    (r'\bсущественным образом\b', 'существенно'),
    (r'\bпринципиальным образом\b', 'принципиально'),
    # «не сводится к X», «не сводимо к X» — оставляем
    # «по этому критерию X сильнее Y» — управленческий язык, оставляем
    # Двойные тире — убираем дублирование оборотов вида "X — то есть Y"
    # Это типичный паттерн ChatGPT — "X — то есть Y". Заменим " – то есть " на " ("
    # Оставлю эту замену осторожно: только в фразах где это явная аннотация
    # «– то есть» в середине → ", то есть"
    (r'\s+–\s+то есть\s+', ', то есть '),
    # «– именно» → «; именно»
    (r'\s+–\s+именно\s+', '; именно '),
    # «именно эта связка» → «эта связка»
    (r'\bименно эта связка\b', 'эта связка'),
    (r'\bИменно эта связка\b', 'Эта связка'),
    # «именно их совместное действие»
    (r'\bИменно их совместное действие\b', 'Их совместное действие'),
    # «именно сочетание условий определяет»
    (r'\bИменно сочетание условий определяет\b', 'Сочетание условий определяет'),
    # «именно с этого момента» — оставим, редкий
    # «как именно» — часто избыточно
    (r'\bкак именно\s+', 'как '),
    # «выступает критическим:»
    (r'\bвыступает критическим:\s+', 'критический: '),
    # Избыточно сложное «принимается с явным указанием на то, что»
    (r'принимается с явным указанием на то, что\b', 'принимается с оговоркой:'),
    # «в горизонте сезона» — оставляем (предметный термин)
    # «по совокупности критериев» — оставляем (управленческий язык)
    # Лишние пробелы
    (r'  +', ' '),
    (r' \.', '.'),
    (r' ,', ','),
]

import re
for pat, repl in replacements:
    t = re.sub(pat, repl, t)

# ============================================================
# 2. «Тот же» / «та же» — частый AI-маркер, оставляем как есть (нечастый и оправданный)
# ============================================================

# ============================================================
# 3. Длинные двойные «– – – »  и «: – » — пунктуационная чистка
# ============================================================
t = re.sub(r':\s+–\s+', ': ', t)  # «:– X» → «: X»
t = re.sub(r'\n\s*\n\s*\n+', '\n\n', t)  # лишние пустые строки

# ============================================================
# 4. Чистка остатков обрывков и проверка пары мест
# ============================================================
# В §3.2 "(включая инструменты §3.2)" в R3 (Удержание) звучит странно — это ссылка изнутри §3.2 на §3.2
t = t.replace("точечная защита чувствительных микролокаций (включая инструменты §3.2)",
              "точечная защита чувствительных микролокаций (см. §3.2)")

# Странное «По этому критерию S2 сильнее S3, S3 сильнее S1 на горизонте перестройки операционной модели»
# (нормально)

# «уже сложившуюся ресурсную базу оператора, а не на её гипотетическое будущее состояние»
# (управленческий язык, ок)

# Сохранить
p.write_text(t, encoding='utf-8')
print(f"Dehumanized. Was {n0}, now {len(t)}, delta {len(t)-n0:+d} chars")
