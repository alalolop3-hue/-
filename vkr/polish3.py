#!/usr/bin/env python3
"""Партия 3: Глава 2.3, 3.2, 3.3, выводы — серьёзные правки логики и дублей."""
from pathlib import Path
import re

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')
n0 = len(t)
fixes = 0

def replace(old, new):
    global t, fixes
    if old in t:
        t = t.replace(old, new, 1)
        fixes += 1
        return True
    return False

# ============================================================
# 1. Таблица 2.1.3,1 → Таблица 2.1.3.1 (моя regex-ошибка)
# ============================================================
replace('Таблица 2.1.3,1.', 'Таблица 2.1.3.1.')

# ============================================================
# 2. §2.3 S3: «режим сокращения» — у нас нет такого режима
# ============================================================
replace(
    'применяет к ним разные режимы конкурентных действий: в одних городах – режим экспансии, в других – режим удержания, в третьих – режим сокращения.',
    'применяет к ним разные режимы конкурентных действий: в одних городах – режим экспансии (R2), в других – режим удержания (R3), в третьих – удержание в ограниченной форме (на регуляторно тяжёлых рынках) или плацдарм (R1) при выходе в новые локации.'
)

# ============================================================
# 3. §2.3.1 Критерий 4: повтор «в рынках R3 ... в рынках R3»
# ============================================================
replace(
    'в рынках R3 – стабилизация маржи через дисциплину расстановки, в рынках R3 – снижение операционной нагрузки без потери существенной выручки. Демонстрационный портфель §2.3.1 показывает направления этой динамики качественно, без претензии на точные финансовые прогнозы.',
    'в рынках R3 «Удержание» – стабилизация маржи через дисциплину расстановки; в рынках с R3 в ограниченной форме (Москва) – снижение операционной нагрузки без потери существенной выручки за счёт исключения зон с отрицательной предельной экономикой. Демонстрационный портфель §2.1.3.6 и финансовая модель §3.4 показывают направления и порядок этой динамики, без претензии на точные финансовые прогнозы.'
)

# ============================================================
# 4. §2.3.1 «причинно неопределённые resources» → «ресурсы» (англицизм)
# ============================================================
replace(
    'относящимся к категории причинно неопределённые resources (Reed, DeFillippi, 1990)',
    'относящимся к категории причинно неопределённых ресурсов (Reed, DeFillippi, 1990)'
)

# ============================================================
# 5. §2.4 Выводы: ссылка «в Главе 3 рассматриваются три сценария» —
# три сценария на самом деле в §2.3
# ============================================================
replace(
    'Этот выбор, в отличие от выбора режима в одном городе, делается на портфельном уровне: в Главе 3 рассматриваются три сценария – сохранение текущей единой логики действий, единый режим с операционной адаптацией и сценарий диверсификации режимов по регионам, – после чего внутри выбранного сценария к разным городам применяются разные режимы конкурентных действий.',
    'Этот выбор, в отличие от выбора режима в одном городе, делается на портфельном уровне: в §2.3 рассмотрены три сценария – сохранение текущей единой логики действий, единый режим с операционной адаптацией и диверсификация режимов по регионам, – из которых обоснован выбор сценария S3. В Главе 3 этот сценарий переводится в проектное содержание: каркас режимов R1–R3, проектный инструмент УПС, финансовая модель и риски.'
)

# ============================================================
# 6. §3.1 R1, Рычаги — обрыв (нет точки)
# ============================================================
replace(
    'режим ориентирован на наблюдение и закрепление, а не на захват доли\nПоказатели.',
    'режим ориентирован на наблюдение и закрепление, а не на захват доли.\nПоказатели.'
)

# ============================================================
# 7. §3.2 ДУБЛЬ блока «Границы расчёта» — старый блок надо удалить
# (он начинается со слов «Управленческая логика УПС допускает количественную оценку
# порядка экономического эффекта» и заканчивается «не даёт отрицательного результата.»,
# после чего идёт мой новый блок «Расчётная цепочка построена в четыре шага»)
# ============================================================
# Найдём дубль
old_dup = re.compile(
    r'Границы расчёта\nУправленческая логика УПС допускает количественную оценку порядка экономического эффекта.{200,3000}?'
    r'не даёт отрицательного результата\.\n',
    re.DOTALL
)
m = old_dup.search(t)
if m:
    print(f"Found dup block: {m.end() - m.start()} chars")
    t = t[:m.start()] + 'Границы расчёта\n' + t[m.end():]
    fixes += 1
else:
    print("No dup block found")

# ============================================================
# 8. §3.2 «демонстрационный портфель §3.2 предполагает» — самоссылка
# ============================================================
replace(
    'Внедрение УПС на пилотном рынке (демонстрационный портфель §3.2 предполагает в этой роли Екатеринбург)',
    'Внедрение УПС на пилотном рынке (демонстрационный портфель §3.3 предполагает в этой роли Екатеринбург)'
)

# ============================================================
# 9. §3.2 «Действие. Активация одного из трёх типов стимулов: Стимул на стороне точки высадки.»
# Структура неконсистентная: первый стимул в строку, остальные с дефисом
# ============================================================
replace(
    'Действие. Активация одного из трёх типов стимулов: Стимул на стороне точки высадки. Пользователю, завершающему поездку, предлагается небольшая выгода (скидка на следующую поездку, бонус, снижение стоимости текущей поездки) при выборе точки завершения, расположенной в зоне дефицита. Это перемещает самокат в нужную точку без отдельной операции ребалансировки.',
    'Действие. Активация одного из трёх типов стимулов.\n– Стимул на стороне точки высадки. Пользователю, завершающему поездку, предлагается небольшая выгода (скидка на следующую поездку, бонус, снижение стоимости текущей поездки) при выборе точки завершения, расположенной в зоне дефицита. Это перемещает самокат в нужную точку без отдельной операции ребалансировки.'
)

# ============================================================
# 10. §3.2 «KPI набор из трёх» а в тексте 4 KPI
# ============================================================
replace(
    'Для оценки пилота УПС в работе предлагается набор из трёх KPI, привязанных к управленческой логике инструмента и допускающих измерение по фактическим данным пилотного рынка.',
    'Для оценки пилота УПС в работе предлагается набор из четырёх KPI, привязанных к управленческой логике инструмента и допускающих измерение по фактическим данным пилотного рынка.'
)

# ============================================================
# 11. §3.3 «введённый в п. 2.4.1» → «§2.1.3.6»
# ============================================================
replace(
    'демонстрационный портфель из пяти городов, введённый в п. 2.4.1: Москва, Санкт-Петербург, Екатеринбург, Краснодар, Новосибирск.',
    'демонстрационный портфель из пяти городов, введённый в §2.1.3.6: Москва, Санкт-Петербург, Екатеринбург, Краснодар, Новосибирск.'
)

# ============================================================
# 12. §3.3 «применимости проектного инструмента §3.3» — самоссылка
# Должно быть на §3.2 (это и есть УПС)
# ============================================================
t = t.replace('применимости проектного инструмента §3.3', 'применимости проектного инструмента §3.2')
fixes += 1

# В тексте §3.3 в разделах по городам было «Применимость §3.3.» — должно быть «Применимость §3.2.»
t = t.replace('Применимость §3.3.', 'Применимость §3.2.')
fixes += 4  # ~4 повторения (5 городов, и в одном уже было исправлено)

# ============================================================
# 13. §2.1.3, параграф (а) «Предельная отдача»: повтор «расширения присутствия»
# и фраза «дополнительный парк не исчезает из стратегического поля» — слабо
# ============================================================
replace(
    'Для оператора кикшеринга стратегическое значение по мере развития рынка приобретает экономический смысл продолжения расширения присутствия. Вопрос состоит в том, способен ли дополнительный парк, более плотное покрытие или выход в новые зоны давать сопоставимый прирост поездок и выручки.',
    'По мере развития рынка стратегическое значение приобретает не само расширение присутствия, а его экономический смысл: способен ли дополнительный парк, более плотное покрытие или выход в новые зоны давать сопоставимый прирост поездок и выручки.'
)

# ============================================================
# 14. §2.1.3.6 «таблица не предписывает режимы» — начало предложения с маленькой
# ============================================================
replace(
    'он сохраняет значение для рынков или локальных зон, где оператор обладает сильной позицией, а также для сопоставления с действиями лидера рынка. таблица не предписывает режимы:',
    'он сохраняет значение для рынков или локальных зон, где оператор обладает сильной позицией, а также для сопоставления с действиями лидера рынка. Таблица не предписывает режимы:'
)

# ============================================================
# 15. Похожая проблема: «Поэтому предпринимательская гибкость Юрента ... та же организационная логика»
# ============================================================
replace(
    'Поэтому предпринимательская гибкость Юрента повышает реализуемость пилота. та же организационная логика создаёт ограничение.',
    'Поэтому предпринимательская гибкость Юрента повышает реализуемость пилота. Однако та же организационная логика создаёт ограничение.'
)

# ============================================================
# Сохранить
# ============================================================
p.write_text(t, encoding='utf-8')
print(f"Applied {fixes} fixes. File: {n0} → {len(t)} ({len(t)-n0:+d})")
