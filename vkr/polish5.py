#!/usr/bin/env python3
"""Партия 5: §3.6 + Заключение — финальные правки."""
from pathlib import Path

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')
n0 = len(t)
fixes = 0

def replace(old, new):
    global t, fixes
    if old in t:
        t = t.replace(old, new, 1)
        fixes += 1
        return True
    return False

# ============================================================
# 1. §3.6 (Выводы по третьей главе): «(§ 2.3)» → «(§2.1.3)»
# ============================================================
replace(
    'Каждый режим описан через однородный набор полей и связан с уровнями факторов I и II (§ 2.3), что делает сопоставимыми диагностики между городами.',
    'Каждый режим описан через однородный набор полей и связан с уровнями факторов I и II (§2.1.3), что делает сопоставимыми диагностики между городами.'
)

# 2. §3.6 «Третья глава, переводит» → «Третья глава переводит» (лишняя запятая)
replace(
    'Третья глава, переводит аналитическую рамку работы',
    'Третья глава переводит аналитическую рамку работы'
)

# ============================================================
# 3. Заключение: «R3 (ограниченная форма) с двумя подтипами – R1 ... и R3 ...»
# Это устаревшая формулировка, мы убрали подтипы R4а/R4б
# ============================================================
replace(
    'R3 «Удержание» – поддержание занятой позиции при приоритете операционной эффективности; R3 (ограниченная форма) с двумя подтипами – R1 (ограниченный вход на рынки, где компания пока не работает) и R3 (ограниченное удержание на рынках уже сложившегося присутствия с высокой ценой сильной позиции).',
    'R3 «Удержание» – поддержание занятой позиции при приоритете операционной эффективности; R3 в ограниченной форме применяется на регуляторно тяжёлых рынках (Москва), где полноформатное удержание сильной позиции экономически нецелесообразно.'
)

# ============================================================
# 4. Заключение: «R3 или R3 при ужесточении регуляторики» — повтор
# ============================================================
replace(
    'Санкт-Петербург как R2 с готовностью перехода к R3 или R3 при ужесточении регуляторики;',
    'Санкт-Петербург как R2 с готовностью перехода к R3 (в полной или ограниченной форме) при ужесточении регуляторики;'
)

# ============================================================
# 5. Заключение: «рассмотренное в раздел о рисках» — кривая фраза
# ============================================================
replace(
    'Проигрыш S3 по критерию операционной исполнимости в горизонте перестройки трактуется как управленческое ограничение, рассмотренное в раздел о рисках, где рассмотрены компенсаторы – функцией портфельного управления',
    'Проигрыш S3 по критерию операционной исполнимости в горизонте перестройки трактуется как управленческое ограничение, рассмотренное в §3.5, где предложены управленческие компенсаторы: функция портфельного управления'
)

# ============================================================
# 6. Заключение: «(см. описание метода ниже)» — теперь должно быть «выше» (раздел методов идёт раньше)
# ============================================================
# уже исправлено

# ============================================================
# 7. §3.5 «6 человек с их фо» — это была заметка от ИА из транскрипта,
# не должно быть в финальном тексте. Проверим.
# (Скорее всего, не попала в работу.)
remaining = t.count('6 человек')
print(f'"6 человек" mentions: {remaining}')

# ============================================================
# 8. Чистка двойных пробелов и пустых строк
# ============================================================
import re
t = re.sub(r'  +', ' ', t)
t = re.sub(r'\n\n\n+', '\n\n', t)

p.write_text(t, encoding='utf-8')
print(f'Applied {fixes} fixes. {n0} → {len(t)} ({len(t)-n0:+d})')
