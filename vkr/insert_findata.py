#!/usr/bin/env python3
"""Вставляю §3.4 Финансовая модель в vkr_final.txt; переименовываю §3.4 Риски → §3.5 и §3.5 Выводы → §3.6"""
from pathlib import Path

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')

# Сначала переименовываю существующие §3.4 и §3.5
old1 = "3.4 Риски сценария S3 и управленческие компенсаторы"
new1 = "3.5 Риски сценария S3 и управленческие компенсаторы"
assert old1 in t, "§3.4 Risks not found"
t = t.replace(old1, new1, 1)

old2 = "3.5 Выводы по третьей главе"
new2 = "3.6 Выводы по третьей главе"
assert old2 in t, "§3.5 Conclusion not found"
t = t.replace(old2, new2, 1)

# Также ссылка "§ 3.4" в тексте о компенсаторах — теперь §3.5
# В §2.6/2.3.1 написано "§ 3.4 обсуждает компенсаторы (поэтапное внедрение...)" — старая §3.4 Риски
t = t.replace("§ 3.4 обсуждает компенсаторы", "§3.5 обсуждает компенсаторы")
t = t.replace("§3.4 обсуждает компенсаторы", "§3.5 обсуждает компенсаторы")
# В §3.2 "что в § 3.4" — компенсаторы рисков:
t = t.replace("компенсаторные механизмы рассматриваются в §3.4", "компенсаторные механизмы рассматриваются в §3.5")
t = t.replace("компенсаторные механизмы рассматриваются в § 3.4", "компенсаторные механизмы рассматриваются в §3.5")
# В §3.2 «рассмотренного в раздел о рисках» (через §3.4) — будет уже §3.5
t = t.replace("выполнении компенсаторов §3.4", "выполнении компенсаторов §3.5")
t = t.replace("выполнении компенсаторов § 3.4", "выполнении компенсаторов §3.5")
# В заключении: «компенсаторов §3.4»
t = t.replace("компенсаторов §3.4", "компенсаторов §3.5")

# Теперь читаю section_3_4.txt и вставляю ПЕРЕД "3.5 Риски сценария S3..."
section = Path('/workspace/vkr/section_3_4.txt').read_text(encoding='utf-8')

# Точка вставки — перед "3.5 Риски сценария S3"
marker = "3.5 Риски сценария S3 и управленческие компенсаторы"
assert marker in t
idx = t.find(marker)
t = t[:idx] + section + "\n" + t[idx:]

p.write_text(t, encoding='utf-8')
print(f"Inserted §3.4 Financial Model. Total now: {len(t)} chars")
