#!/usr/bin/env python3
"""Возвращаю KFU, SW и финмодель блоки в правильные места в ОСНОВНОМ ТЕКСТЕ.
Все вставки делаются по ПОСЛЕДНЕМУ вхождению маркера в файле (rfind),
чтобы попасть в тело работы, а не в оглавление.
"""
import re
from pathlib import Path

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')
n0 = len(t)

# ============================================================
# 1. KFU блок — ПЕРЕД "2.1.3 Стратегически значимые различия..." в основном тексте.
# ============================================================
kfu_block = """Ключевые факторы успеха на зрелом рынке кикшеринга. На основе сравнения трёх операторов и интервью с экспертом А. можно зафиксировать ключевые факторы успеха (КФУ) оператора кикшеринга на зрелой стадии рынка: (1) фактическая доступность самоката в нужной точке и в нужное время – качество покрытия с учётом микрогеометрии города и колебаний спроса; (2) экономика на единицу парка – соотношение выручки и операционных издержек на один самокат за сезон, определяющее устойчивость модели при удорожании капитала; (3) операционная исполнимость – способность поддерживать связку парка, доступности и утилизации без избыточного роста стоимости ребалансировки и обслуживания. Из этих трёх первый – доступность покрытия – критический: пользовательский выбор оператора реализуется в момент, когда самокат либо есть в точке, либо нет, и эта механика напрямую конвертируется в долю поездок и выручки оператора. Этот вывод фиксируется в качестве отправной точки проектного инструмента «Управление покрытием через стимулы» (§3.2).
Региональные гэпы МТС Юрент относительно лидера. Сравнение операторов выявляет систематическое отставание МТС Юрент от Whoosh по выручке на самокат (49,4 vs 66,8 тыс. руб./год на единицу парка) и по утилизации; разрыв возникает не столько из-за меньшего размера парка, сколько из-за более низкой эффективности уже размещённого парка. В региональном разрезе по данным эксперта А. (поквартальная отчётность по 86 субъектам РФ за 2024 и 9 месяцев 2025) гэп различается: в Москве МТС Юрент работает с утилизацией 1 073 поездки на самокат в год (сопоставимо со среднеоператорской Whoosh); в Санкт-Петербурге – 609; в Краснодаре – 564; в Екатеринбурге – 319 (почти вдвое ниже среднего по оператору); в Новосибирске – 277 при темпах роста +129 % YoY за 9 мес. 2025 г. Гэп между лидером и МТС Юрент по утилизации сильнее выражен в городах с резервом плотности и зрелым спросом (Екатеринбург, Краснодар) и слабее – на регуляторно перегруженных и насыщенных рынках (Москва), где сам предельный эффект расширения для всех операторов снижается. Закрытие гэпа не сводится к универсальному наращиванию парка и требует дифференциации действий по типам региональных рынков – к этому ведёт логика §2.1.3 и §2.3.

"""

marker_213 = "2.1.3 Стратегически значимые различия между региональными рынками: принцип отбора"
idx = t.rfind(marker_213)
assert idx >= 0, "marker 2.1.3 not found"
# Подстрахуемся, что это НЕ строка в оглавлении: в оглавлении заголовок без ":" (см. чистое оглавление "2.1.3 Стратегически значимые различия между региональными рынками")
# Реальный заголовок в тексте имеет ": принцип отбора" → именно так задан marker_213.
# Найдено правильно.
t = t[:idx] + kfu_block + t[idx:]
print(f"[1/3] KFU block inserted at idx {idx}. Now {len(t)}")

# ============================================================
# 2. SW блок — ПЕРЕД "2.3 Стратегический выбор" в основном тексте.
# В оглавлении строка ровно "2.3 Стратегический выбор". В тексте — тоже самое.
# Поэтому используем КОНТЕКСТНЫЙ маркер: подзаголовок 2.3 идёт после
# раздела 2.2, в конце которого фраза «соотнести свои цифровые, операционные
# и экосистемные ресурсы с разными режимами присутствия.»
# ============================================================
sw_block = """Сводный вывод по внутренней среде: сильные и слабые стороны.

Сильные стороны МТС Юрент:
●	интеграция в экосистему ПАО «МТС»: доступ к клиентской базе ~80 млн абонентов, единый MTS ID, экосистемные каналы коммуникации, подписочная модель через МТС Premium, обезличенная геоаналитика;
●	технологический контур: собственная разрабатываемая платформа после приобретения Eleven, телематика парка, базовая инфраструктура push-стимулирования (предпосылка УПС);
●	операционная база: парк ~120 тыс. СИМ, присутствие в 187 локациях, отстроенные процедуры обслуживания и приложение с действующей пользовательской базой;
●	предпринимательская гибкость: компактная команда, короткий контур принятия решений, готовность пилотировать продуктовые механики.

Слабые стороны МТС Юрент:
●	централизованная управленческая логика: продуктовые, маркетинговые и операционные решения принимаются преимущественно из центра, что снижает чувствительность к различиям между региональными рынками;
●	слабая формализация регионального управления: отсутствует устойчивая процедура сопоставимого различения городов и назначения режимов присутствия; решения по портфелю принимаются как набор отдельных кейсов (экспертная оценка);
●	ограниченная локальная управленческая инфраструктура: дефицит выделенных функций региональной экспертизы и координации;
●	систематическое отставание по операционной эффективности: выручка на самокат и утилизация ниже, чем у Whoosh, что отражает не только размер парка, но и качество управления уже размещёнными активами.

Внутренняя оценка через рамку динамических способностей. В терминах концепции dynamic capabilities (Teece, Pisano, Shuen, 1997) МТС Юрент демонстрирует развитый «операционный» блок способностей – отстроенные процессы исполнения core-бизнеса (обслуживание парка, приложение, операционная отчётность) – и одновременно начальную зрелость второго блока: способности улавливать сигналы об изменениях рынка и воспроизводимо перестраивать конфигурацию ресурсов под эти изменения. Дефицит второго блока создаёт разрыв, на который отвечает дифференцированная логика управления портфелем региональных рынков: она превращает текущие сигналы по городам (изменения спроса, регуляторики, конкурентного поля) в воспроизводимые решения о режиме присутствия, а не в разовые корректировки. Сценарий S3 (§2.3) не только реализует ресурсный потенциал компании, но и систематически развивает её динамические способности.

"""

marker_23_context = "соотнести свои цифровые, операционные и экосистемные ресурсы с разными режимами присутствия."
idx = t.rfind(marker_23_context)
assert idx >= 0, "marker 2.3 context not found"
# вставка ПОСЛЕ этой фразы (после её "\n")
nl_idx = t.find('\n', idx)
if nl_idx < 0: nl_idx = len(t)
t = t[:nl_idx+1] + "\n" + sw_block + t[nl_idx+1:]
print(f"[2/3] SW block inserted after idx {nl_idx}. Now {len(t)}")

# ============================================================
# 3. Финмодель — ПЕРЕД "3.5 Риски сценария S3" в основном тексте.
# В оглавлении мы это название не оставили (после очистки оглавление чистое).
# Найдём последнее вхождение, оно же единственное (заголовок раздела).
# ============================================================
section_text = Path('/workspace/vkr/section_3_4.txt').read_text(encoding='utf-8')

marker_35 = "3.5 Риски сценария S3 и управленческие компенсаторы"
idx = t.rfind(marker_35)
assert idx >= 0, "marker 3.5 Risks not found"
# Вставляем ПЕРЕД "3.5 Риски..."
t = t[:idx] + section_text + "\n" + t[idx:]
print(f"[3/3] Financial model inserted at idx {idx}. Now {len(t)}")

# Сохранить
p.write_text(t, encoding='utf-8')
print(f"\nDONE. Was {n0}, now {len(t)} ({len(t)-n0:+d})")
