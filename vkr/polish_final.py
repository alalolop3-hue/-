#!/usr/bin/env python3
"""Финальный пас: остатки AI-маркеров, мелкие шероховатости."""
from pathlib import Path
import re

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')
n0 = len(t)
fixes = 0

# Глобальные замены AI-клише (оставшиеся после предыдущих чисток)
patterns = [
    # «Применение пяти критериев в §2.3 строится не как простое сложение баллов» → проще
    (r'Применение пяти критериев в §2\.3 строится не как простое сложение баллов, а как согласованное сопоставление',
     'Пять критериев применяются не как формальное сложение баллов, а как согласованное сопоставление'),
    # «По этому критерию» — повторяется 5 раз в §2.3.1, оставляем как структурный маркер
    # «Критерий ставит вопрос о том» — клише, в §2.3.1 повторяется 4 раза. Стандартная управленческая формулировка, оставляем.
    # «нужен для рассмотрения» — лишний канцелярит
    (r'Критерий нужен для рассмотрения реализуемости сценария',
     'Критерий проверяет реализуемость сценария'),
    # «Критерий оценивает, насколько сценарий предполагает реальную, а не декларативную способность»
    (r'Критерий оценивает, насколько сценарий предполагает реальную, а не декларативную способность',
     'Критерий проверяет, опирается ли сценарий на реальную способность'),
    # «Логика ресурсного подхода исходит из того, что устойчивое преимущество фирмы строится» — клише
    (r'Логика ресурсного подхода исходит из того, что',
     'Ресурсная теория исходит из того, что'),
    # «Для выбора сценария это вопрос» — повторяется в каждом критерии (5 раз). Оставляем — параллелизм здесь полезен.
    # «Сценарий, требующий ... по этому критерию слабее сценария, опирающегося...» — параллельная конструкция,
    # повторяется в каждом критерии. Оставляем (это структурный приём).
    # Несколько «именно» — оставляем минимально (это смысловое слово в части мест)
    # «значительной части стоимости позиции» — канцелярит
    (r'значительная часть стоимости позиции МТС Юрент в зрелых рынках',
     'значительная часть преимущества МТС Юрент в зрелых рынках'),
    # «Чувствительность выбора к смещению акцента между критериями» — лучше «Чувствительность выбора к весам критериев»
    (r'Чувствительность выбора к смещению акцента между критериями',
     'Чувствительность выбора к весам критериев'),
    # «обсуждается в §2.3 отдельно» (про чувствительность критериев) — повторяется. Оставляем.
    # «не сводится к выбору единого темпа географической экспансии»
    # — нормально, оставляем
    # Лишний «При этом» — глобально заменяем на пустоту
    (r'\. При этом ', '. '),
    # «Иначе говоря,» — уже почищено
    # «существенным образом» / «принципиальным образом» — почищено
    # «отдельную задачу» — нормально
    # «Это та область, где S3 имеет управленческое ограничение» — длинно
    (r'Это та область, где S3 имеет управленческое ограничение и где компенсаторные механизмы рассматриваются в §3\.5',
     'Компенсаторы для этого ограничения рассмотрены в §3.5'),
    # «Иначе говоря» — оставшееся
    (r'\bИначе говоря,?\s+', ''),
    # «Стоит отметить» — оставшиеся
    (r'\bСтоит отметить,?\s+', ''),
    # Лишние «Поэтому» подряд в начале предложений — оставим, потому что это нормальный связочный союз
]

for pat, repl in patterns:
    new_t = re.sub(pat, repl, t)
    if new_t != t:
        diff = len(t) - len(new_t)
        t = new_t
        fixes += 1

# Дополнительные точечные замены
specific = [
    ('Демонстрационный портфель из пяти городов выполняет иллюстративную функцию и не заменяет полного описания всех 187 локаций',
     'Демонстрационный портфель из пяти городов выполняет иллюстративную функцию и не заменяет полную карту 187 локаций'),
    # В заключении: «Третья глава переводит аналитическую рамку работы (Глава 1) и систему стратегически
    # значимого различения рынков (Глава 2) в стратегическое решение и проектное содержание для МТС Юрент:
    # выбор сценария обращения с портфелем, каркас режимов, демонстрационный портфель и проектный инструмент
    # образуют единую конструкцию, в которой различия между региональными рынками используются как основа более
    # точной конкурентной логики оператора.» — длинное предложение, разбить
    ('Третья глава переводит аналитическую рамку работы (Глава 1) и систему стратегически значимого различения рынков (Глава 2) в стратегическое решение и проектное содержание для МТС Юрент: выбор сценария обращения с портфелем, каркас режимов, демонстрационный портфель и проектный инструмент образуют единую конструкцию, в которой различия между региональными рынками используются как основа более точной конкурентной логики оператора.',
     'Третья глава переводит аналитическую рамку Главы 1 и систему различения рынков Главы 2 в стратегическое решение и проектное содержание для МТС Юрент. Выбор сценария, каркас режимов, демонстрационный портфель и проектный инструмент образуют единую конструкцию, в которой различия между региональными рынками используются как основа более точной конкурентной логики.'),
]
for o, n in specific:
    if o in t:
        t = t.replace(o, n, 1)
        fixes += 1

# Финальная чистка пунктуации
t = re.sub(r'\s+\.', '.', t)
t = re.sub(r'\s+,', ',', t)
t = re.sub(r'  +', ' ', t)
t = re.sub(r'\n\n\n+', '\n\n', t)

p.write_text(t, encoding='utf-8')
print(f'Applied {fixes} fixes. {n0} → {len(t)} ({len(t)-n0:+d})')
