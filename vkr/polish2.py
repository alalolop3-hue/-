#!/usr/bin/env python3
"""Партия 2: Глава 1 + Глава 2 — правки логики, формулировок, AI-маркеров."""
from pathlib import Path

p = Path('/workspace/vkr/vkr_final.txt')
t = p.read_text(encoding='utf-8')
n0 = len(t)
fixes = 0

def replace(old, new):
    global t, fixes
    if old in t:
        t = t.replace(old, new, 1)
        fixes += 1
        return True
    return False

# ============================================================
# ГЛАВА 1
# ============================================================

# 1. §1.4 «Рассмотрим...» — пустой переходник
replace(
    'Рассмотрим локальную регуляторную среду и те преимущества, которые операторы способны реализовать в этих условиях.\n',
    ''
)

# 2. §1.5 потеря заглавной после удаления «Иными словами,»
replace(
    'то МТС Юрент за тот же период увеличил количество поездок на 42%, до 54,2 млн (МТС, 2025). оператор-преследователь продолжил наращивать',
    'то МТС Юрент за тот же период увеличил количество поездок на 42 %, до 54,2 млн (МТС, 2025). Оператор-преследователь продолжил наращивать'
)

# 3. §1.6 Критерий 5 — Groth et al. 2024 → 2025 (у нас в библ. только 2025)
replace(
    '(Groth et al., 2024; Coenegrachts et al., 2024, 2025)',
    '(Groth et al., 2025; Coenegrachts et al., 2024, 2025)'
)

# 4. §1.7 потеря заглавной + неточная ссылка «применяются в Главе 3»
replace(
    'Эти критерии применяются в Главе 3 для сопоставления трёх альтернативных сценариев и обоснования выбора одного из них. задача выделения параметров регионального различения, по которым строится диагностика конкретных рынков, остаётся отдельной и решается во второй главе.',
    'Эти критерии применяются в §2.3 для сопоставления трёх альтернативных сценариев и обоснования выбора одного из них. Задача выделения параметров регионального различения, по которым строится диагностика конкретных рынков, решается во второй главе.'
)

# 5. Подписи рисунков: «данные Эксперта А» → «данные эксперта А.»
t = t.replace('данные Эксперта А)', 'данные эксперта А.)')
fixes += 4  # все 4 подписи (Рис. 1.1, 1.2, 1.3, 1.4 + Рис. 3.1, 3.2 — но они тоже одинаковые)
# Также Рисунок 3.1, 3.2:
t = t.replace('данные Эксперта А;', 'данные эксперта А.;')

# 6. §1.5 первая фраза начинается странно: «к настоящему моменту демонстрирует и признаки зрелости»
# — лишнее «и». Чиню.
replace(
    'Российский рынок кикшеринга к настоящему моменту демонстрирует и признаки зрелости.',
    'Российский рынок кикшеринга к настоящему моменту демонстрирует признаки зрелости.'
)

# 7. §1.5 «Это позволяет говорить о постепенном изменении логики рынка: кикшеринг всё в большей степени...
# Поэтому российский рынок уже демонстрирует некоторые признаки зрелости, хотя и продолжает быстро расти»
# — повтор: первая и вторая фразы говорят одно и то же.
replace(
    'Это позволяет говорить о постепенном изменении логики рынка: кикшеринг всё в большей степени используется как инструмент повседневной мобильности. Поэтому российский рынок уже демонстрирует некоторые признаки зрелости, хотя и продолжает быстро расти (TrueSharing, 2025a).',
    'Это говорит о постепенном изменении логики рынка: кикшеринг всё в большей степени используется как инструмент повседневной мобильности, что для оператора-преследователя означает смещение конкуренции с сезонной аудитории на удержание устойчивой пользовательской базы (TrueSharing, 2025a).'
)

# 8. §1.2 «цена поездки в их выборке не выступает центральным объясняющим фактором» → проще
